#!/usr/bin/env bash
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)

bash -n "$ROOT/install.sh"
bash -n "$ROOT/uninstall.sh"
bash -n "$ROOT/status.sh"
bash -n "$ROOT/manage.sh"
bash -n "$ROOT/install-oneclick.sh"
bash -n "$ROOT/iptv-routeros-sync"
